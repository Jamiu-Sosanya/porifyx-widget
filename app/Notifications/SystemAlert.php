<?php

namespace App\Notifications;

use Illuminate\Bus\Queueable;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Notifications\Messages\MailMessage;
use Illuminate\Notifications\Notification;

class SystemAlert extends Notification implements ShouldQueue
{
    use Queueable;

    protected string $alertType;
    protected array $data;

    /**
     * Create a new notification instance.
     */
    public function __construct(string $alertType, array $data)
    {
        $this->alertType = $alertType;
        $this->data = $data;
    }

    /**
     * Get the notification's delivery channels.
     */
    public function via(object $notifiable): array
    {
        return ['mail', 'database'];
    }

    /**
     * Get the mail representation of the notification.
     */
    public function toMail(object $notifiable): MailMessage
    {
        $message = (new MailMessage)
            ->subject($this->getAlertSubject())
            ->greeting('System Alert')
            ->line($this->getAlertMessage());

        // Add action button if applicable
        if ($action = $this->getAlertAction()) {
            $message->action($action['text'], $action['url']);
        }

        $message->line('This alert was automatically generated by your PoriFyx Widget system.')
            ->salutation('Best regards, The PoriFyx Team');

        return $message;
    }

    /**
     * Get the array representation of the notification.
     */
    public function toArray(object $notifiable): array
    {
        return [
            'alert_type' => $this->alertType,
            'data' => $this->data,
            'message' => $this->getAlertMessage(),
            'action' => $this->getAlertAction(),
        ];
    }

    /**
     * Get the alert subject.
     */
    protected function getAlertSubject(): string
    {
        return match ($this->alertType) {
            'conversation_volume_drop' => 'Alert: Conversation Volume Drop Detected',
            'conversation_volume_spike' => 'Alert: Conversation Volume Spike Detected',
            'lead_quality_drop' => 'Alert: Lead Quality Drop Detected',
            'hot_lead_drop' => 'Alert: Hot Lead Generation Drop Detected',
            'ab_test_significant_difference' => 'Alert: A/B Test Shows Significant Difference',
            default => 'System Alert',
        };
    }

    /**
     * Get the alert message.
     */
    protected function getAlertMessage(): string
    {
        return match ($this->alertType) {
            'conversation_volume_drop' => "Your widget '{$this->data['widget_name']}' has experienced a {$this->data['drop_percentage']}% drop in conversations today. Current: {$this->data['current_count']}, Historical average: {$this->data['historical_average']}.",
            'conversation_volume_spike' => "Your widget '{$this->data['widget_name']}' has experienced a {$this->data['spike_percentage']}% spike in conversations today. Current: {$this->data['current_count']}, Historical average: {$this->data['historical_average']}.",
            'lead_quality_drop' => "Your lead quality has dropped by {$this->data['drop_percentage']}%. Current average score: {$this->data['current_average']}, Historical average: {$this->data['historical_average']} (based on {$this->data['lead_count']} leads today).",
            'hot_lead_drop' => "Your hot lead generation has dropped significantly. Current hot lead percentage: {$this->data['current_percentage']}%, Historical: {$this->data['historical_percentage']}% (based on {$this->data['lead_count']} leads today).",
            'ab_test_significant_difference' => "Your A/B test '{$this->data['test_name']}' shows a significant difference in conversion rates. Variant A: {$this->data['variant_a_rate']}, Variant B: {$this->data['variant_b_rate']} (difference: {$this->data['difference']}). Consider stopping the test and using variant {$this->data['recommended_winner']}.",
            default => 'An unusual system event has been detected.',
        };
    }

    /**
     * Get the alert action.
     */
    protected function getAlertAction(): ?array
    {
        return match ($this->alertType) {
            'conversation_volume_drop', 'conversation_volume_spike' => [
                'text' => 'View Widget Analytics',
                'url' => url('/widgets'), // You might want to make this more specific
            ],
            'lead_quality_drop', 'hot_lead_drop' => [
                'text' => 'View Leads',
                'url' => url('/leads'),
            ],
            'ab_test_significant_difference' => [
                'text' => 'View A/B Test Results',
                'url' => url('/widgets'), // You might want to make this more specific
            ],
            default => null,
        };
    }
}